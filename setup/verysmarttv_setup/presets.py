"""The community debloat presets: the index, how a TV's `getprop` values are matched to one (DESIGN.md §17).

`presets/index.json` is generated by `tools/dev/build_presets_index.py` from each list's header, slug and
`tv.json`, with `mine_tokens` below, so the grammar that writes the index and the one that reads a TV's
properties stay one. Matching tiers (§17.3): exact (model or device equals a token), board (board or product
equals a token, same brand), brand+os (same brand, SDK within one), brand (same brand). A model or device
that equals a token of a list written for another brand (MediaTek and Realtek reference boards such as `m7322`
or `rtd2841a` are reported as the device by sets of many brands) ranks last, as "other brand", below every
list of the TV's own brand, and is never pre-selected.
"""
import json
import re
from pathlib import Path

GENERIC = {"tv", "android", "google", "fire", "os", "sdk", "api", "firmware", "build", "version", "model",
           "device", "product", "board", "codename", "the", "and", "with", "set", "stick", "box", "smart",
           "inch", "series", "list", "debloat", "patchwall", "launcher", "release", "update", "pro",
           # prose that follows "device", "model" or "product" in a header without naming a code
           "family", "string", "name", "names", "authentication", "info", "preferences", "number", "credentials",
           "too", "has", "have", "had", "rebooted", "does", "was", "were", "differs", "service", "services", "code",
           "usage", "lockcontroller", "controlservice", "that", "this", "which", "where", "when", "from", "into",
           "only", "also", "its", "itself", "not", "but", "for", "are", "can", "may", "will", "still", "then",
           "line", "lines", "user", "owner", "settings", "setting", "input", "inputs", "manager", "store", "play"}
# "Android TV 10" / "Google TV 12" / "Fire OS 7 (Android 9)" -> the SDK level, when the header has none.
ANDROID_SDK = {"5": 21, "5.0": 21, "5.1": 22, "6": 23, "6.0": 23, "7": 24, "7.0": 24, "7.1": 25, "8": 26, "8.0": 26,
               "8.1": 27, "9": 28, "9.0": 28, "10": 29, "11": 30, "12": 31, "12.1": 32, "13": 33, "14": 34,
               "15": 35, "16": 36}
TIERS = ("exact", "board", "brand+os", "brand", "other-brand")
TIER_TEXT = {"exact": "exact model match", "board": "same board, different model name",
             "brand+os": "same brand and Android version: check the list",
             "brand": "same brand: check the list",
             "other-brand": "same model or device name, but a list for another brand: check it"}


def normalise(word: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (word or "").lower()).strip("-")


def brand_key(brand: str) -> str:
    """The first word of a brand, normalised: "Amazon Fire TV" and `ro.product.brand=Amazon` meet."""
    words = normalise(brand).split("-")
    return words[0] if words else ""


def mine_tokens(header: str, slug: str, tv: str) -> list:
    """Identifiers a TV may report, from the header's first line and tv.json's `tv` (quoted strings,
    parenthesised codes, hyphenated codes, words that mix letters and digits), from the whole header the
    word after device/product/board/model/codename, plus the slug and the slug without its brand. Each is
    lower-cased with non-alphanumerics collapsed to `-`; prose, generic words and numbers are dropped, and a
    word without a digit (a codename such as `tarzan`) counts only when a keyword or the slug named it."""
    first = header.splitlines()[0] if header else ""
    front = f"{first}\n{tv}"
    coded, named = [], []
    coded += re.findall(r'"([^"]{2,40})"', front)
    coded += re.findall(r"[`']([A-Za-z0-9][A-Za-z0-9_.-]{1,40})[`']", front)
    for inner in re.findall(r"\(([^()]{2,80})\)", front):
        for piece in re.split(r"[,;/]| or ", inner):
            piece = piece.strip().strip(".")
            if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_. -]{1,40}", piece) and re.search(r"[A-Za-z]", piece):
                coded.append(piece)
    coded += re.findall(r"\b([A-Z][A-Za-z]*[-_][A-Z0-9][A-Za-z0-9_-]{1,30})\b", front)
    coded += re.findall(r"\b([A-Za-z]*\d[A-Za-z0-9_-]*[A-Za-z][A-Za-z0-9_-]*|[A-Za-z]+\d[A-Za-z0-9_-]*)\b", front)
    # Firmware build ids (QTG3.200305.006.2591): a TV's ro.build.version.incremental, when the header has it.
    coded += re.findall(r"\b([A-Z]{2,5}\d\.\d{6}\.\d{3}(?:\.\d+)?)\b", header)
    named += re.findall(r"\b(?:device|product|board|model|codename|platform)\s*[:=]?\s*\"?([A-Za-z0-9][A-Za-z0-9_.-]{1,40})",
                        header, re.I)
    named += re.findall(r"ro\.(?:product|build)\.(?:model|device|board|name|product)\s*[:=]\s*\"?([A-Za-z0-9][A-Za-z0-9_.-]{1,40})",
                        header, re.I)
    named.append(slug)
    parts = slug.split("-")
    if len(parts) > 1:
        named.append("-".join(parts[1:]))
    tokens = []
    for word, needs_digit in [(w, True) for w in coded] + [(w, False) for w in named]:
        token = normalise(word)
        if usable_token(token, needs_digit) and token not in tokens:
            tokens.append(token)
    return tokens


NOISE = re.compile(r"^(sdk|api|android|google-tv|fire-os|firmware|keycode|priority|build|version|user|users|batch"
                   r"|\d+-gb|\d+-mb)(-.*)?$"
                   r"|^(wi-fi|hdmi-cec|tv-host|usb-c|4k|8k|1080p|720p|hdr|hdr10|dolby-vision|wifi|bluetooth)$")


def usable_token(token: str, needs_digit: bool) -> bool:
    if not 3 <= len(token) <= 40 or token in GENERIC or token.isdigit() or NOISE.match(token):
        return False
    parts = token.split("-")
    if len(parts) > 5:
        return False
    if re.search(r"\d", token):
        return True
    return not needs_digit and len(parts) <= 2


def sdk_from_text(header: str, os_text: str):
    m = re.search(r"\b(?:SDK|API)\s*(\d{2})\b", header, re.I)
    if m:
        return int(m.group(1))
    m = re.search(r"\b(?:Android(?: TV)?|Google TV|Fire OS \d(?: \(Android)?)\s*(\d{1,2}(?:\.\d)?)\b", f"{header}\n{os_text}")
    if m:
        return ANDROID_SDK.get(m.group(1), ANDROID_SDK.get(m.group(1).split(".")[0]))
    return None


class Preset:
    def __init__(self, entry: dict, root: Path):
        self.slug = entry["slug"]
        self.tv = entry.get("tv", "")
        self.brand = entry.get("brand", "")
        self.os = entry.get("os", "")
        self.header = entry.get("header", "")
        self.tokens = list(entry.get("tokens", []))
        self.sdk = entry.get("sdk")
        self.packages = entry.get("packages", 0)
        self.stock_launcher = entry.get("stock_launcher")
        self.notes = entry.get("notes", "")
        self.path = root / entry["path"]

    def text(self) -> str:
        return self.path.read_text(encoding="utf-8-sig", errors="replace")

    def __repr__(self):
        return f"<Preset {self.slug}>"


class Match:
    def __init__(self, preset: Preset, tier: str, sdk_distance, hits: int = 0):
        self.preset, self.tier, self.sdk_distance, self.hits = preset, tier, sdk_distance, hits

    @property
    def text(self):
        return TIER_TEXT[self.tier]

    def __repr__(self):
        return f"<Match {self.preset.slug} {self.tier}>"


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def load_index(root: Path = None) -> list:
    root = root or repo_root()
    data = json.loads((root / "presets" / "index.json").read_text(encoding="utf-8"))
    return [Preset(entry, root) for entry in data["presets"]]


def by_slug(presets, slug):
    return next((p for p in presets if p.slug == slug), None)


def match(props: dict, presets: list) -> list:
    """Ranked matches for a TV's getprop values: tier order, then the number of identifiers in common
    (firmware, board and product on top of the model), then SDK distance, then package count. A model or
    device match against a list whose brand is another one (a reference-board name the TV reports as its
    device) is demoted to the last tier; a TV that reports no brand keeps its exact matches."""
    model = normalise(props.get("ro.product.model", ""))
    device = normalise(props.get("ro.product.device", ""))
    board = normalise(props.get("ro.product.board", ""))
    product = normalise(props.get("ro.build.product", "") or props.get("ro.product.name", ""))
    firmware = normalise(props.get("ro.build.version.incremental", ""))
    display = normalise(props.get("ro.build.display.id", ""))
    brand = brand_key(props.get("ro.product.brand", "") or props.get("ro.product.manufacturer", ""))
    maker = brand_key(props.get("ro.product.manufacturer", ""))
    sdk = props.get("ro.build.version.sdk", "")
    sdk = int(sdk) if str(sdk).isdigit() else None

    found = []
    for preset in presets:
        tokens = set(preset.tokens)
        same_brand = bool(brand) and brand_key(preset.brand) in {brand, maker}
        other_brand = bool(brand) and bool(brand_key(preset.brand)) and not same_brand
        distance = abs(preset.sdk - sdk) if (preset.sdk is not None and sdk is not None) else 99
        hits = sum(1 for value in (model, device, board, product, firmware, display) if value and value in tokens)
        tier = None
        if (model and model in tokens) or (device and device in tokens):
            tier = "other-brand" if other_brand else "exact"
        elif same_brand and ((board and board in tokens) or (product and product in tokens)):
            tier = "board"
        elif same_brand and distance <= 1:
            tier = "brand+os"
        elif same_brand:
            tier = "brand"
        if tier:
            found.append(Match(preset, tier, distance, hits))
    found.sort(key=lambda m: (TIERS.index(m.tier), -m.hits, m.sdk_distance, -m.preset.packages, m.preset.slug))
    return found


def suggestion(matches: list):
    """The one preset offered as the pre-selected answer: only an exact match (ADR-027)."""
    return matches[0] if matches and matches[0].tier == "exact" else None
